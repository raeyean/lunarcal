#!/usr/bin/env node
/**
 * Generates targets/shared/AlmanacData.swift from lunar-javascript, the engine
 * the phone app uses, so the Swift engine (widget fallback + watch) gives the
 * same Month Pillar and 宜/忌 (issue #41, ADR 0001).
 *
 * Run from the repo root after upgrading lunar-javascript:
 *   node scripts/verify-swift-almanac/generate-data.js
 * then run scripts/verify-swift-almanac/verify.sh.
 */
const fs = require('fs');
const path = require('path');
const { Solar, LunarUtil } = require('lunar-javascript');
const version = require('lunar-javascript/package.json').version;

// Solar-term table range. Month Pillars are correct from FIRST_YEAR + 1 on:
// early January needs the previous year's 大雪.
const FIRST_YEAR = 2019;
const LAST_YEAR = 2060;

// lunar-javascript names terms in simplified Chinese; the Swift table and the
// UI use traditional.
const TRADITIONAL = {
  惊蛰: '驚蟄', 谷雨: '穀雨', 小满: '小滿', 芒种: '芒種', 处暑: '處暑',
};
const trad = (name) => TRADITIONAL[name] || name;

function jieqiForYear(year) {
  const out = [];
  const d = new Date(Date.UTC(year, 0, 1));
  while (d.getUTCFullYear() === year) {
    const y = d.getUTCFullYear(), m = d.getUTCMonth() + 1, day = d.getUTCDate();
    const name = Solar.fromYmd(y, m, day).getLunar().getJieQi();
    if (name) out.push([m, day, trad(name)]);
    d.setUTCDate(d.getUTCDate() + 1);
  }
  if (out.length !== 24) throw new Error(`${year}: expected 24 solar terms, got ${out.length}`);
  return out;
}

const years = [];
for (let y = FIRST_YEAR; y <= LAST_YEAR; y++) {
  const rows = [];
  const terms = jieqiForYear(y);
  for (let i = 0; i < terms.length; i += 4) {
    rows.push('            ' + terms.slice(i, i + 4).map(([m, d, n]) => `(${m},${d},"${n}")`).join(','));
  }
  years.push(`        ${y}: [\n${rows.join(',\n')}\n        ]`);
}

const yiJi = LunarUtil.YI_JI;
const yiJiRows = [];
for (let i = 0; i < yiJi.length; i += 10) {
  yiJiRows.push('        ' + yiJi.slice(i, i + 10).map((s) => JSON.stringify(s)).join(', '));
}

const dayYiJi = LunarUtil.DAY_YI_JI;
if (!/^[0-9A-F=:,]+$/.test(dayYiJi)) throw new Error('DAY_YI_JI has unexpected characters');
const chunks = dayYiJi.match(/.{1,100}/g);

const swift = `// GENERATED by scripts/verify-swift-almanac/generate-data.js from
// lunar-javascript ${version}. Do not edit by hand.
//
// The 宜/忌 rule data (YI_JI, DAY_YI_JI) and the solar-term dates come from
// lunar-javascript by 6tail, MIT License:
// https://github.com/6tail/lunar-javascript

enum AlmanacData {
    /// First and last Gregorian year in \`jieqiDates\`. Month Pillars (and so
    /// 宜/忌) are only computed for dates from \`jieqiFirstYear + 1\` through
    /// \`jieqiLastYear\`.
    static let jieqiFirstYear = ${FIRST_YEAR}
    static let jieqiLastYear = ${LAST_YEAR}

    /// Solar terms per Gregorian year as (month, day, name), UTC+8 dates.
    static let jieqiDates: [Int: [(Int, Int, String)]] = [
${years.join(',\n')}
    ]

    /// lunar-javascript LunarUtil.YI_JI: activity names, indexed by the
    /// two-digit hex codes in \`dayYiJi\`.
    static let yiJi: [String] = [
${yiJiRows.join(',\n')}
    ]

    /// lunar-javascript LunarUtil.SHEN_SHA[0], returned when no rule matches.
    static let none = ${JSON.stringify(LunarUtil.SHEN_SHA[0])}

    /// lunar-javascript LunarUtil.DAY_YI_JI: 宜/忌 rules keyed by the day's
    /// 干支 index, then by Month Pillar index (both as two-digit hex).
    static let dayYiJi: String = [
${chunks.map((c) => '        "' + c + '"').join(',\n')}
    ].joined()
}
`;

const out = path.join(__dirname, '..', '..', 'targets', 'shared', 'AlmanacData.swift');
fs.writeFileSync(out, swift);
console.log(`wrote ${path.relative(process.cwd(), out)}: ${LAST_YEAR - FIRST_YEAR + 1} years of solar terms, ${yiJi.length} activities, ${dayYiJi.length} rule chars`);
